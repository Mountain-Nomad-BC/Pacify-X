"""Canonical mutating-producer registry (Phase 1C).

Every mutating producer in the repository must either

1. acquire/use the canonical lease + effect-intent path, or
2. be explicitly proven read-only / non-mutating (or otherwise exempt) with a
   reason drawn from a closed vocabulary.

This module is the single owner of that classification. It:

* discovers the real mutating producers from the canonical effect-surface owner
  (``runtime.effect_surface``) rather than from an invented list;
* classifies each producer as ``leased`` or ``exempt`` with a proven reason;
* publishes the classification to ``registry/mutating_producers.json``;
* **fails closed** on any discovered producer that has no classification.

The registry is a source-authority projection, not a second effect owner: the
effect surface itself remains owned by ``runtime/effect_surface.py``.
"""

