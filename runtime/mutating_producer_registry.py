PUBLICATION_OWNER = "runtime/guarded_registry_projection.py"
PUBLICATION_FUNCTION = "publish_guarded_registry_projection"


def _delegated_publication_verdict(
    root: Path, relative: str, records: list[dict[str, object]] | None = None
) -> dict[str, str] | None:
    """B1: does this caller purely delegate its durable effect to the publication owner?

    Verified from the caller's own source on every evaluation, so neither a stale table
    entry nor a rename can grant the classification. Four facts are required:

    1. the source imports `publish_guarded_registry_projection` from the canonical module;
    2. it calls it;
    3. it has no `filesystem_mutation` record outside its own publication call sites;
    4. the owner module exists and still defines the function.

    Anything else returns None, which leaves the producer unresolved — the fail-closed
    direction, because a caller that also writes directly is a mixed producer and needs a
    different contract (B6-D2), not this one.

    `records` may carry one shared effect inventory from the caller. Re-scanning the whole
    repository for every delegated caller made the census quadratic: `default_classification`
    runs once per mutating producer, and each delegated caller re-parsed every source file.
    """
    import ast as _ast

    path = root / relative
    owner = root / PUBLICATION_OWNER
    if not path.is_file():
        return None
    source = path.read_text(encoding="utf-8-sig")

    # The guarded-registry delegation and the packaging-projection delegation are two
    # independent publication surfaces. Neither may be skipped merely because the producer
    # does not use the other one.
    if not owner.is_file() or PUBLICATION_FUNCTION not in owner.read_text(encoding="utf-8"):
        return _packaging_projection_verdict(root, relative, source)

    tree = _ast.parse(source)
    imported = False
    call_lines: set[int] = set()
    for node in _ast.walk(tree):
        if isinstance(node, _ast.ImportFrom) and node.module == "runtime.guarded_registry_projection":
            if any(alias.name == PUBLICATION_FUNCTION for alias in node.names):
                imported = True
        elif isinstance(node, _ast.Import):
            if any(alias.name == "runtime.guarded_registry_projection" for alias in node.names):
                imported = True
        if isinstance(node, _ast.Call):
            target = node.func
            name = target.attr if isinstance(target, _ast.Attribute) else getattr(
                target, "id", "")
            if name == PUBLICATION_FUNCTION:
                call_lines.add(node.lineno)
    if not imported or not call_lines:
        return _packaging_projection_verdict(root, relative, source)

    if records is None:
        from .effect_surface import discover_effect_surfaces

        records = discover_effect_surfaces(root)
    calls_publication = False
    for record in records:
        if record["path"] != relative:
            continue
        if str(record["effect"]) != "filesystem_mutation":
            continue
        if int(record["line"]) not in call_lines:
            return None
        calls_publication = True
    if calls_publication:
        return {"classification": "exempt", "reason": "delegated_publication"}
    return _packaging_projection_verdict(root, relative, source)


# The generated packaging block in pyproject.toml is rendered by the canonical renderer below.
# A skill script that is *shipped* through that block has its lifecycle published by the
# package projection, not by the script. This is the same delegation fact as above, measured
# on the packaging surface instead of the guarded-registry surface.
PACKAGING_RENDERER = "scripts/migration/sync_skill_packaging.py"
PACKAGING_BLOCK_START = "# BEGIN GENERATED OPERATIONAL SKILL DATA FILES"
PACKAGING_BLOCK_END = "# END GENERATED OPERATIONAL SKILL DATA FILES"


_PACKAGING_TRACKED: dict[str, bool] = {}


def _tracked_skill(root: Path, skill_root: str) -> bool:
    """Cached `git ls-files` answer: is this skill directory tracked at all?"""
    import subprocess

    key = f"{root}\0{skill_root}"
    if key in _PACKAGING_TRACKED:
        return _PACKAGING_TRACKED[key]
    try:
        tracked = subprocess.run(
            ["git", "ls-files", "--", skill_root],
            cwd=str(root),
            capture_output=True,
            text=True,
            timeout=30,
        )
    except (OSError, subprocess.SubprocessError):
        _PACKAGING_TRACKED[key] = False
        return False
    result = tracked.returncode == 0 and bool(tracked.stdout.strip())
    _PACKAGING_TRACKED[key] = result
    return result


def _packaging_projection_verdict(root: Path, relative: str, source: str) -> dict[str, str] | None:
    """Delegated publication measured against the generated packaging block.

    Every condition is read from the current tree, never from a stored label:

    1. the script is an immutable authored asset of a tracked skill (`.px/skills/<id>/...`,
       no `..`, and the skill directory is tracked by Git);
    2. the script defines no import-time work: all executable statements sit inside function
       definitions, so importing it has no effect and only an explicit call reaches a write;
    3. the script's module code mutates nothing it owns, which the caller already established
       by finding no mutation outside its publication call sites;
    4. the canonical packaging renderer exists and still emits the block;
    5. the current pyproject lists this exact file inside that generated block, so the
       package projection is what carries the shipped bytes.
    """
    import ast as _ast

    parts = relative.split("/")
    if len(parts) < 3 or parts[0] != ".px" or parts[1] != "skills" or ".." in parts:
        return None
    skill_root = "/".join(parts[:3])
    renderer = root / PACKAGING_RENDERER
    pyproject = root / "pyproject.toml"
    if not renderer.is_file() or not pyproject.is_file():
        return None
    renderer_source = renderer.read_text(encoding="utf-8")
    if PACKAGING_BLOCK_START not in renderer_source or ".px/skills" not in renderer_source:
        return None
    if not _tracked_skill(root, skill_root):
        return None
    text = pyproject.read_text(encoding="utf-8")
    if text.count(PACKAGING_BLOCK_START) != 1 or text.count(PACKAGING_BLOCK_END) != 1:
        return None
    block = text.split(PACKAGING_BLOCK_START, 1)[1].split(PACKAGING_BLOCK_END, 1)[0]
    if f'"{relative}"' not in block:
        return None
    tree = _ast.parse(source)
    # A script below the repository root must put that root on `sys.path` before it can import
    # `runtime`; the insertion is in-process only. It is admitted only when the path expression
    # is anchored at the script's own location, so no caller-supplied or environment path is.
    for node in tree.body:
        if isinstance(node, _ast.Expr) and _import_path_insertion(node, tree):
            continue
        if isinstance(node, (_ast.Import, _ast.ImportFrom)):
            # Module-level imports are real. `_import_inert` decides which; the producer's own
            # `sys.path` binding above only makes the imported module resolvable.
            if not _import_inert(node):
                return None
            continue
        if isinstance(node, (_ast.FunctionDef, _ast.AsyncFunctionDef, _ast.ClassDef)):
            continue
        if isinstance(node, _ast.Expr) and isinstance(node.value, _ast.Constant):
            continue
        if isinstance(node, _ast.Assign) and node.value is not None and _value_inert(node.value):
            continue
        if isinstance(node, _ast.AnnAssign) and (node.value is None or _value_inert(node.value)):
            continue
        if isinstance(node, (_ast.If, _ast.Try)) and _guard_block_inert(node):
            continue
        return None
    return {"classification": "exempt", "reason": "delegated_publication"}


def _guard_block_inert(node: object) -> bool:
    """A top-level `if`/`try` that performs no work when the module is imported.

    Two shapes qualify:

    * the standard script guard `if __name__ == '__main__': ...` — importing the file runs
      nothing in its body, so whatever the body does is reachable only on explicit execution;
    * a module-level `try:` around imports — the handlers' *type expressions* are not executed
      at import, but every handler body is, so handler bodies must be inert themselves.

    Any other top-level condition may run work at import and is not inert.
    """
    import ast as _ast

    if isinstance(node, _ast.If):
        test = node.test
        return bool(
            isinstance(test, _ast.Compare)
            and isinstance(test.left, _ast.Name)
            and test.left.id == "__name__"
            and len(test.comparators) == 1
            and isinstance(test.comparators[0], _ast.Constant)
            and test.comparators[0].value == "__main__"
        )
    if not isinstance(node, _ast.Try):
        return False
    # The handlers' *type* expressions are not executed at import; only their bodies are.
    body = list(node.body)
    body.extend(node.orelse)
    body.extend(node.finalbody)
    body.extend(node.handlers)
    return all(_statement_inert(item) for item in body)


def _statement_inert(node: object) -> bool:
    """A statement that performs no work when the module is imported."""
    import ast as _ast

    if isinstance(node, (_ast.FunctionDef, _ast.AsyncFunctionDef, _ast.ClassDef, _ast.Pass)):
        return True
    if isinstance(node, (_ast.Import, _ast.ImportFrom)):
        return _import_inert(node)
    if isinstance(node, _ast.ExceptHandler):
        return all(_statement_inert(item) for item in node.body)
    if isinstance(node, _ast.Expr) and isinstance(node.value, _ast.Constant):
        return True
    if isinstance(node, _ast.Raise):
        # `raise SystemExit(main())` inside a `__main__` guard: the guard itself is what keeps
        # it from running on import, so the call is scoped to the guarded branch. A bare
        # `raise` at module level is not inert.
        return _guard_body_scoped(node)
    if isinstance(node, _ast.Assign):
        return _value_inert(node.value)
    if isinstance(node, _ast.AnnAssign):
        return node.value is None or _value_inert(node.value)
    return False


def _guard_body_scoped(node: object) -> bool:
    """`raise SystemExit(main())` / `raise SystemExit(code)` — the standard guarded exit."""
    import ast as _ast

    if not isinstance(node, _ast.Raise) or node.exc is None:
        return False
    exc = node.exc
    if not isinstance(exc, _ast.Call):
        return isinstance(exc, _ast.Name) and exc.id == "SystemExit"
    func = exc.func
    return isinstance(func, _ast.Name) and func.id == "SystemExit"


def _import_inert(node: object) -> bool:
    """An import that cannot execute a sibling's code by itself.

    A plain `import x` / `from x import y` runs `x/__init__`. That is inert when `x` is a
    standard-library module or a dotted runtime package; it is not proven inert for a
    sibling-relative import, so those keep the producer unresolved.
    """
    import ast as _ast

    if isinstance(node, _ast.Import):
        names = [alias.name for alias in node.names]
    else:
        names = [getattr(node, "module", None) or ""]
        if isinstance(node, _ast.ImportFrom) and (node.level or 0) > 0:
            return False
    if not names:
        return False
    for name in names:
        head = name.split(".", 1)[0]
        if head in {"runtime", "__future__"}:
            continue
        if head in INERT_STDLIB_MODULES:
            continue
        return False
    return True


def _import_path_insertion(node: object, tree: object) -> bool:
    """`sys.path.insert(0, str(<the producer's own repository>))` — no filesystem write.

    A script that lives below the repository root must put the root on `sys.path` before it can
    import `runtime`; that lookup is in-process only. The path expression must be anchored at
    the script's own location — `str(__file__…)` directly, or a name whose module-level
    assignment is so anchored (`ROOT = Path(__file__).resolve().parents[4]`). A caller-supplied
    directory or an environment value is never admitted by this.
    """
    import ast as _ast

    if not isinstance(node, _ast.Expr) or not isinstance(node.value, _ast.Call):
        return False
    call = node.value
    func = call.func
    if not (isinstance(func, _ast.Attribute) and func.attr == "insert"):
        return False
    receiver = func.value
    if not (
        isinstance(receiver, _ast.Attribute)
        and receiver.attr == "path"
        and isinstance(receiver.value, _ast.Name)
        and receiver.value.id == "sys"
    ):
        return False
    if len(call.args) != 2 or not isinstance(call.args[0], _ast.Constant):
        return False
    expression = call.args[1]
    if _is_module_anchor(expression):
        return True
    if isinstance(expression, _ast.Call) and isinstance(expression.func, _ast.Name):
        # `str(ROOT)` / `ROOT.as_posix()` over an anchored name is still anchored.
        if expression.func.id in {"str", "repr"} and expression.args:
            expression = expression.args[0]
    if isinstance(expression, _ast.Name):
        return _name_bound_to_own_root(tree, expression.id)
    return False


def _name_bound_to_own_root(tree: object, name: str) -> bool:
    """True when module-level assignments of `name` are anchored at the producer."""
    import ast as _ast

    values: list[object] = []
    for node in getattr(tree, "body", ()):
        if isinstance(node, _ast.Assign):
            if any(isinstance(t, _ast.Name) and t.id == name for t in node.targets):
                values.append(node.value)
        elif isinstance(node, _ast.AnnAssign) and node.value is not None:
            if isinstance(node.target, _ast.Name) and node.target.id == name:
                values.append(node.value)
    return bool(values) and any(_is_module_anchor(value) for value in values)


def _is_module_anchor(node: object) -> bool:
    import ast as _ast

    return any(isinstance(item, _ast.Name) and item.id == "__file__" for item in _ast.walk(node))


def _module_binds_own_root(tree: object) -> bool:
    """True when a module-level assignment names the producer's own location."""
    import ast as _ast

    for node in getattr(tree, "body", ()):
        values = []
        if isinstance(node, _ast.Assign):
            values.append(node.value)
        elif isinstance(node, _ast.AnnAssign) and node.value is not None:
            values.append(node.value)
        if any(_is_module_anchor(value) for value in values):
            return True
    return False


def _value_inert(value: object) -> bool:
    """A module-level value that creates no file and starts no process.

    Comprehensions, generators and lambdas are values: building one runs nothing. A call is
    inert when it is one of the names below — compile, convert, or locate a path; none of them
    opens, creates, renames or deletes a file and none spawns a process. Every other call keeps
    the producer unresolved rather than being assumed harmless.
    """
    import ast as _ast

    if isinstance(value, (_ast.ListComp, _ast.SetComp, _ast.DictComp, _ast.GeneratorExp, _ast.Lambda)):
        return True
    for node in _ast.walk(value):
        if isinstance(node, (_ast.Await, _ast.Yield, _ast.YieldFrom)):
            return False
        if not isinstance(node, _ast.Call):
            continue
        func = node.func
        name = func.attr if isinstance(func, _ast.Attribute) else getattr(func, "id", "")
        if name not in INERT_BUILD_CALLS:
            return False
    return True


# Standard-library modules whose import has no side effects relied on as state. Membership is
# checked against the interpreter the producer would run on, not against a list of names that
# "look" safe: an unlisted module keeps the producer unresolved rather than being assumed
# harmless.
INERT_STDLIB_MODULES = frozenset(sys.stdlib_module_names) - {
    "antigravity", "this", "__hello__", "__phello__", "idlelib", "turtledemo",
}

# Builtins and constructors that compute, compile or locate a value without touching the
# filesystem or starting a process. Membership is a fact about each callable, not a pattern:
# anything absent keeps the producer unresolved.
INERT_BUILD_CALLS = frozenset(
    {
        "tuple", "list", "dict", "set", "frozenset", "str", "int", "float", "bool",
        "bytes", "len", "sorted", "reversed", "enumerate", "zip", "range", "min", "max",
        "sum", "any", "all", "abs", "round", "repr", "format", "join", "strip", "split",
        "rsplit", "casefold", "lower", "upper", "removeprefix", "removesuffix",
        "compile", "escape", "Path", "PurePath", "PurePosixPath", "joinpath", "resolve",
        "parents", "parent", "with_name", "with_suffix", "as_posix", "anchor", "cwd",
        "values", "keys", "items", "get", "partition", "startswith", "endswith", "count",
    }
)


def _matches_native_owner(root: Path, relative: str) -> bool:
    """A project filename cannot impersonate the shipped native custody owner."""
    from .archive_io import reject_path_links
    candidate = root / relative
    native = Path(__file__).resolve().parents[1] / relative
    if not candidate.is_file() or not native.is_file():
        return False
    try:
        reject_path_links(candidate)
    except (OSError, ValueError):
        return False
    return hashlib.sha256(candidate.read_bytes()).digest() == hashlib.sha256(native.read_bytes()).digest()


def _registry_owned_verdict(root: Path, relative: str) -> Mapping[str, str] | None:
    """Resolve a producer that writes repository state owned by a registered custodian.

    This is the only authority that can act on the accepted B7 ownership decisions. It is
    deliberately narrow:

    * the ownership registry must be in the approved state;
    * at least one resource must have a registered custodian;
    * the producer must be a member of that resource's verified writer set — the registry
      never claims a resource the matrix did not already attribute to this file;
    * the custodian must not itself be a writer of the group it owns.

    It confers no write authority: a writer still needs a per-run governed grant.
    """
    import json as _json

    registry_path = root / OWNERSHIP_REGISTRY_RELATIVE
    if not registry_path.is_file():
        return None
    try:
        document = _json.loads(registry_path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    if not isinstance(document, dict) or document.get("state") != "approved_custodian_registrations":
        return None
    resources = document.get("resources")
    if not isinstance(resources, list):
        return None
    for item in resources:
        if not isinstance(item, dict) or item.get("registration_state") != "registered":
            continue
        group = item.get("group_members")
        record = item.get("record") or {}
        owner = record.get("accountable_owner")
        if not isinstance(group, list) or not owner:
            continue
        normalised = {_normalize(str(member)) for member in group}
        if relative not in normalised:
            continue
        if _normalize(str(owner)) in normalised:
            continue
        # A registered entry is only authoritative if it satisfies the accepted
        # resource contract. Without this the registry conferred custody from a
        # record carrying as little as {resource_id, accountable_owner}: no
        # authorization, lifecycle, concurrency, recovery or approval event.
        # Proof: deleting every other field still yielded "exempt". Fails closed.
        from .runtime_state_ownership import validate_approved_resource_record
        if validate_approved_resource_record(record, group_members=group):
            continue
        return {"classification": "exempt", "reason": "owned_durable_resource"}
    return None


def default_classification(
    root: Path,
    relative: str,
    effects: tuple[str, ...],
    *,
    records: list[dict[str, object]] | None = None,
) -> Mapping[str, str] | None:
    """Return current source-backed classification, never an import assertion.

    Native custody owners bootstrap their own controls. Every other mutation
    remains unclassified until its real guarded call path has been reviewed.
    Atomic output, a canonical import, and a generated destination do not prove
    scope leasing or effect-intent admission.

    `records` is an optional shared effect inventory for delegated-publication checks.
    Omitting it preserves the previous per-producer scan behavior.
    """
    relative = _normalize(relative)
    if relative in GUARDED_MUTATING_OWNERS and _matches_native_owner(root, relative):
        return {"classification": "leased", "reason": "canonical_lease_intent_owner"}
    if relative in NATIVE_CONTROL_CUSTODY_OWNERS and _matches_native_owner(root, relative):
        return {"classification": "exempt", "reason": "canonical_control_custody_owner"}
    # The approved ownership registry is consulted only after every reviewed local authority
    # has declined, so it can add resolutions but never override an existing classification.
    owned = _registry_owned_verdict(root, relative)
    if owned is not None:
        return owned
    # Output-root grants: a producer resolves only when every destination it writes is
    # authorized. One destination never authorizes another, and this path is never used for
    # process or network producers.
    from .output_root_classification import output_root_verdict

    granted = output_root_verdict(root, relative, effects)
    if granted is not None:
        return granted
    # Reviewed delegation requires both caller and owner to match their approved bytes.
    # Structural routing proof cannot override an expired review fingerprint.
    delegated = REVIEWED_DELEGATED_PUBLICATION.get(relative)
    if relative not in REVIEWED_DELEGATED_PUBLICATION:
        from .mutating_producer_custody_reviewed import (
            DECLARED_OUTPUT_TARGET_RECONCILED as _RECONCILED,
        )

        # The packaging projection is a second, independent publication surface: a shipped
        # skill script whose lifecycle is published by the generated pyproject block. It is
        # established from the live tree on every run, so it needs no reviewed table, and it
        # is consulted only after every reviewed authority above has declined.
        #
        # A producer the predicate *qualified* already has an individual review decision, so
        # this whole-file property must never override it. A producer the predicate **audited and
        # rejected** is a different case: that rejection says "this is not a caller-directed
        # output", it does not say "this is not published by the package projection". Such a
        # producer is therefore eligible, but only after the rejected branch above has declined.
        shipped = None
        if relative.startswith(".px/skills/") and relative not in _RECONCILED:
            shipped = _packaging_projection_verdict(
                root, relative, (root / relative).read_text(encoding="utf-8-sig")
                if (root / relative).is_file() else ""
            )
        if shipped is not None:
            return shipped
    if delegated is not None:
        caller, owner = root / relative, root / delegated["owner"]
        if (caller.is_file() and owner.is_file()
                and hashlib.sha256(caller.read_bytes()).hexdigest() == delegated["source_sha256"]
                and hashlib.sha256(owner.read_bytes()).hexdigest() == delegated["owner_sha256"]):
            return {"classification": "leased", "reason": "canonical_lease_intent_delegate"}
        return None
    control = REVIEWED_CONTROL_CUSTODY.get(relative)
    path = root / relative
    if control is not None and path.is_file():
        if hashlib.sha256(path.read_bytes()).hexdigest() == control["sha256"]:
            return {"classification": "exempt", "reason": control["reason"]}

    from .mutating_producer_custody_reviewed import (
        DECLARED_OUTPUT_PRECEDENCE,
        DECLARED_OUTPUT_TARGET_RECONCILED,
        REVIEWED_PRODUCER_CUSTODY,
    )
    # Predicate-reconciled declared_output_target entries (PX-OS-1067) take precedence
    # over the generated table for the producers they cover, so a stale
    # `declared_output_target` label cannot substitute itself for the predicate. A
    # producer the predicate rejected is not in this mapping and stays unresolved.
    # Each entry pins the exact source it judged, so drift invalidates it.
    # Precedence is decided first. A producer the predicate audited and rejected was also
    # added to precedence so the generated table cannot re-promote it — but the generated
    # table is itself in REVIEWED_PRODUCER_CUSTODY, so checking the reconciled mapping
    # first let a drifted old entry survive ahead of the rejection. A rejected producer
    # must resolve to nothing regardless of which reviewed table mentions it.
    reconciled = DECLARED_OUTPUT_TARGET_RECONCILED.get(relative)
    if reconciled is not None:
        # A reconciled producer resolves only from a live, matching pinned entry; drift
        # or an audit that did not qualify it returns None and never falls through to a
        # generated label.
        if path.is_file() and hashlib.sha256(path.read_bytes()).hexdigest() == reconciled["sha256"]:
            return {
                "classification": reconciled["classification"],
                "reason": reconciled["reason"],
            }
        return None
    if relative in DECLARED_OUTPUT_PRECEDENCE and relative not in REVIEWED_DELEGATED_PUBLICATION:
        # This producer was judged by the predicate and did not qualify; the generated
        # table's label must not re-promote it. Report the exact failing condition.
        #
        # A producer whose complete publication path was separately reviewed as delegating
        # to the guarded projection is a different contract: it is `leased` because of that
        # reviewed call path, not because of a stale label, so it is not withheld here.
        return None
    reviewed = REVIEWED_PRODUCER_CUSTODY.get(relative)
    if reviewed is not None and path.is_file():
        if hashlib.sha256(path.read_bytes()).hexdigest() == reviewed["sha256"]:
            return {"classification": reviewed["classification"], "reason": reviewed["reason"]}
    expected = REVIEWED_READ_ONLY_SOURCE_SHA256.get(relative)
    path = root / relative
    if expected is not None and path.is_file():
        if hashlib.sha256(path.read_bytes()).hexdigest() == expected:
            return {"classification": "exempt", "reason": "read_only_classifier"}
    return None


def _load_registry(path: Path) -> dict[str, object]:
    if not path.is_file():
        return {"schema_version": SCHEMA_VERSION, "producers": {}}
    from .archive_io import reject_path_links
    from .json_io import read_bounded_bytes
    reject_path_links(path)
    document = json.loads(bytes(read_bounded_bytes(path, max_bytes=16 * 1024 * 1024)).decode("utf-8"))
    if not isinstance(document, dict):
        raise MutatingProducerError("mutating producer registry is not an object")
    if document.get("schema_version") != SCHEMA_VERSION:
        raise MutatingProducerError("mutating producer registry schema is unsupported")
    producers = document.get("producers")
    if not isinstance(producers, dict):
        raise MutatingProducerError("mutating producer registry has no producers map")
    return document


def validate_registry(
    root: Path, *, records: list[dict[str, object]] | None = None
) -> dict[str, object]:
    """Validate the published registry against the discovered producers.

    Fails closed: any discovered producer absent from the registry, or any
    registry entry whose classification/reason is invalid, is reported as an
    error and the result is not valid.

    `records` is an optional shared effect inventory; `validate_effect_surfaces` passes
    the scan it already performed so a gate run does not rescan per producer.
    """
    root = root.resolve()
    registry_path = root / REGISTRY_RELATIVE
    errors: list[str] = []
    document = _load_registry(registry_path)
    declared = document.get("producers") if isinstance(document, dict) else None
    if not isinstance(declared, dict):
        declared = {}

    discovered = discover_mutating_producers(root, records=records)
    for relative, effects in discovered.items():
        entry = declared.get(relative)
        if not isinstance(entry, dict):
            errors.append(f"{relative}: unclassified mutating producer ({', '.join(effects)})")
            continue
        current = default_classification(root, relative, effects, records=records)
        if current is None:
            errors.append(f"{relative}: no current source-backed custody classification")
        elif any(entry.get(key) != current[key] for key in ("classification", "reason")):
            errors.append(f"{relative}: published classification differs from current source authority")
        expected_source = hashlib.sha256((root / relative).read_bytes()).hexdigest()
        if entry.get("source_sha256") != expected_source:
            errors.append(f"{relative}: source custody evidence is missing or stale")
        if entry.get("effects") != ", ".join(effects):
            errors.append(f"{relative}: declared effect denominator differs from discovery")
        classification = entry.get("classification")
        reason = entry.get("reason")
        if classification not in {"leased", "exempt"}:
            errors.append(f"{relative}: invalid classification {classification!r}")
        if reason not in EXEMPTION_REASONS and reason != "canonical_lease_intent_owner":
            errors.append(f"{relative}: invalid exemption reason {reason!r}")

    stale = sorted(set(declared) - set(discovered))
    errors.extend(f"{relative}: stale producer entry" for relative in stale)
    counts: dict[str, int] = {}
    for entry in declared.values():
        if isinstance(entry, dict):
            key = str(entry.get("classification"))
            counts[key] = counts.get(key, 0) + 1
    return {
        "schema_version": SCHEMA_VERSION,
        "valid": not errors,
        "discovered": len(discovered),
        "declared": len(declared),
        "stale_entries": stale,
        "counts": dict(sorted(counts.items())),
        "errors": errors,
    }


def build_registry(
    root: Path,
    *,
    records: list[dict[str, object]] | None = None,
    self_source_sha256: str | None = None,
) -> dict[str, Any]:
    """Build the complete classification for every discovered producer.

    `self_source_sha256` lets a publisher declare the exact bytes of this module that are
    doing the publishing. The publisher rewrites its own file's entry to that digest, because
    an entry hashed from disk could never match the file it is embedded in once the entry
    text itself lives there.

    Producers that the structural rules cannot classify are returned as
    ``unclassified`` so the caller can fail closed rather than guess.

    `records` is an optional shared effect inventory. Without it this function rescans
    the repository once; the canonical census passes its own scan so the whole run does
    a bounded number of scans instead of one per delegated producer.
    """
    root = root.resolve()
    discovered = discover_mutating_producers(root, records=records)
    producers: dict[str, dict[str, str]] = {}
    unclassified: list[str] = []
    for relative, effects in discovered.items():
        derived = default_classification(root, relative, effects, records=records)
        if derived is None:
            unclassified.append(relative)
            continue
        producers[relative] = {**derived, "effects": ", ".join(effects),
            "source_sha256": (
                self_source_sha256
                if self_source_sha256 is not None and relative == SELF_RELATIVE
                else hashlib.sha256((root / relative).read_bytes()).hexdigest()
            )}
    return {
        "schema_version": SCHEMA_VERSION,
        "producers": producers,
        "unclassified": sorted(unclassified),
    }




def publish_registry(root: Path, *, admission_event_id: str | None = None) -> dict[str, object]:
    """Publish the registry. Refuses while any producer remains unclassified."""
    root = root.resolve()
    built = build_registry(root)
    unclassified: list[str] = built["unclassified"]
    if unclassified:
        raise MutatingProducerError(
            "refusing to publish: unclassified mutating producers: "
            + ", ".join(unclassified)
        )
    producers: dict[str, dict[str, str]] = built["producers"]
    image = {
        "schema_version": SCHEMA_VERSION,
        "authority": (
            "Phase 1C classification of every mutating producer as leased (uses the "
            "canonical lease+intent path) or exempt (proven reason). Fails closed on "
            "any new unclassified producer."
        ),
        "producer_count": len(producers),
        "producers": producers,
    }
    from .guarded_registry_projection import (
        GuardedProjectionError, publish_guarded_registry_projection)
    try:
        result = publish_guarded_registry_projection(root, REGISTRY_RELATIVE, image,
            admission_event_id=admission_event_id)
    except GuardedProjectionError as error:
        raise MutatingProducerError(str(error)) from error
    return {**result, "producer_count": len(producers)}
