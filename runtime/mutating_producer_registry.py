# Closed vocabulary of proof reasons for an exemption. A producer that cannot be
# classified as `leased` must cite exactly one of these and the evidence for it.
EXEMPTION_REASONS = (
    "canonical_lease_intent_delegate",
    "canonical_control_custody_owner",
    "canonical_control_audit_custody",
    "protected_identity_custody",
    "independent_recovery_custody",
    # The module IS the canonical lease/intent/mutation-authority owner.
    "canonical_lease_intent_owner",
    # The module only reads; its "mutation" surface is a bounded probe/temp file
    # created and removed within one scope (owned-ephemeral reclamation).
    "owned_ephemeral_reclamation",
    # The module writes only to a caller-declared output target (for example a
    # `--out` argument); it owns no durable state itself.
    "declared_output_target",
    # The module is a pure projection/generator whose output is GENERATED (never
    # canonical authority) and is regenerated by its own producer.
    "generated_projection_producer",
    # The module is a test/benchmark/verification harness not on a runtime path.
    "non_runtime_harness",
    # The module's effect is a bounded read-only probe with no write.
    "read_only_probe",
    # The module is a read-only classifier whose only mutation-shaped call is a
    # string/dataclass helper (str.replace, dataclasses.replace), not a write.
    "read_only_classifier",
)

