def _matches_native_owner(root: Path, relative: str) -> bool:
    """A project filename cannot impersonate the shipped native custody owner."""
    from .archive_io import reject_path_links
    candidate = root / relative
    native = Path(__file__).resolve().parents[1] / relative
    if not candidate.is_file() or not native.is_file():
        return False
    try:
        reject_path_links(candidate)
    except (OSError, ValueError):
        return False
    return hashlib.sha256(candidate.read_bytes()).digest() == hashlib.sha256(native.read_bytes()).digest()


def default_classification(
    root: Path, relative: str, effects: tuple[str, ...]
) -> Mapping[str, str] | None:
    """Return current source-backed classification, never an import assertion.

    Native custody owners bootstrap their own controls. Every other mutation
    remains unclassified until its real guarded call path has been reviewed.
    Atomic output, a canonical import, and a generated destination do not prove
    scope leasing or effect-intent admission.
    """
    relative = _normalize(relative)
    if relative in GUARDED_MUTATING_OWNERS and _matches_native_owner(root, relative):
        return {"classification": "leased", "reason": "canonical_lease_intent_owner"}
    if relative in NATIVE_CONTROL_CUSTODY_OWNERS and _matches_native_owner(root, relative):
        return {"classification": "exempt", "reason": "canonical_control_custody_owner"}
    delegated = REVIEWED_DELEGATED_PUBLICATION.get(relative)
    if delegated is not None:
        caller, owner = root / relative, root / delegated["owner"]
        if (caller.is_file() and owner.is_file()
                and hashlib.sha256(caller.read_bytes()).hexdigest() == delegated["source_sha256"]
                and hashlib.sha256(owner.read_bytes()).hexdigest() == delegated["owner_sha256"]):
            return {"classification": "leased", "reason": "canonical_lease_intent_delegate"}
        return None
    control = REVIEWED_CONTROL_CUSTODY.get(relative)
    path = root / relative
    if control is not None and path.is_file():
        if hashlib.sha256(path.read_bytes()).hexdigest() == control["sha256"]:
            return {"classification": "exempt", "reason": control["reason"]}
    from .mutating_producer_custody_reviewed import REVIEWED_PRODUCER_CUSTODY
    reviewed = REVIEWED_PRODUCER_CUSTODY.get(relative)
    if reviewed is not None and path.is_file():
        if hashlib.sha256(path.read_bytes()).hexdigest() == reviewed["sha256"]:
            return {"classification": reviewed["classification"], "reason": reviewed["reason"]}
    expected = REVIEWED_READ_ONLY_SOURCE_SHA256.get(relative)
    path = root / relative
    if expected is not None and path.is_file():
        if hashlib.sha256(path.read_bytes()).hexdigest() == expected:
            return {"classification": "exempt", "reason": "read_only_classifier"}
    return None


def _load_registry(path: Path) -> dict[str, object]:
    if not path.is_file():
        return {"schema_version": SCHEMA_VERSION, "producers": {}}
    from .archive_io import reject_path_links
    from .json_io import read_bounded_bytes
    reject_path_links(path)
    document = json.loads(bytes(read_bounded_bytes(path, max_bytes=16 * 1024 * 1024)).decode("utf-8"))
    if not isinstance(document, dict):
        raise MutatingProducerError("mutating producer registry is not an object")
    if document.get("schema_version") != SCHEMA_VERSION:
        raise MutatingProducerError("mutating producer registry schema is unsupported")
    producers = document.get("producers")
    if not isinstance(producers, dict):
        raise MutatingProducerError("mutating producer registry has no producers map")
    return document


def validate_registry(root: Path) -> dict[str, object]:
    """Validate the published registry against the discovered producers.

    Fails closed: any discovered producer absent from the registry, or any
    registry entry whose classification/reason is invalid, is reported as an
    error and the result is not valid.
    """
    root = root.resolve()
    registry_path = root / REGISTRY_RELATIVE
    errors: list[str] = []
    document = _load_registry(registry_path)
    declared = document.get("producers") if isinstance(document, dict) else None
    if not isinstance(declared, dict):
        declared = {}

    discovered = discover_mutating_producers(root)
    for relative, effects in discovered.items():
        entry = declared.get(relative)
        if not isinstance(entry, dict):
            errors.append(f"{relative}: unclassified mutating producer ({', '.join(effects)})")
            continue
        current = default_classification(root, relative, effects)
        if current is None:
            errors.append(f"{relative}: no current source-backed custody classification")
        elif any(entry.get(key) != current[key] for key in ("classification", "reason")):
            errors.append(f"{relative}: published classification differs from current source authority")
        expected_source = hashlib.sha256((root / relative).read_bytes()).hexdigest()
        if entry.get("source_sha256") != expected_source:
            errors.append(f"{relative}: source custody evidence is missing or stale")
        if entry.get("effects") != ", ".join(effects):
            errors.append(f"{relative}: declared effect denominator differs from discovery")
        classification = entry.get("classification")
        reason = entry.get("reason")
        if classification not in {"leased", "exempt"}:
            errors.append(f"{relative}: invalid classification {classification!r}")
        if reason not in EXEMPTION_REASONS and reason != "canonical_lease_intent_owner":
            errors.append(f"{relative}: invalid exemption reason {reason!r}")

    stale = sorted(set(declared) - set(discovered))
    errors.extend(f"{relative}: stale producer entry" for relative in stale)
    counts: dict[str, int] = {}
    for entry in declared.values():
        if isinstance(entry, dict):
            key = str(entry.get("classification"))
            counts[key] = counts.get(key, 0) + 1
    return {
        "schema_version": SCHEMA_VERSION,
        "valid": not errors,
        "discovered": len(discovered),
        "declared": len(declared),
        "stale_entries": stale,
        "counts": dict(sorted(counts.items())),
        "errors": errors,
    }


def build_registry(root: Path) -> dict[str, Any]:
    """Build the complete classification for every discovered producer.

    Producers that the structural rules cannot classify are returned as
    ``unclassified`` so the caller can fail closed rather than guess.
    """
    root = root.resolve()
    discovered = discover_mutating_producers(root)
    producers: dict[str, dict[str, str]] = {}
    unclassified: list[str] = []
    for relative, effects in discovered.items():
        derived = default_classification(root, relative, effects)
        if derived is None:
            unclassified.append(relative)
            continue
        producers[relative] = {**derived, "effects": ", ".join(effects),
            "source_sha256": hashlib.sha256((root / relative).read_bytes()).hexdigest()}
    return {
        "schema_version": SCHEMA_VERSION,
        "producers": producers,
        "unclassified": sorted(unclassified),
    }




def publish_registry(root: Path, *, admission_event_id: str | None = None) -> dict[str, object]:
    """Publish the registry. Refuses while any producer remains unclassified."""
    root = root.resolve()
    built = build_registry(root)
    unclassified: list[str] = built["unclassified"]
    if unclassified:
        raise MutatingProducerError(
            "refusing to publish: unclassified mutating producers: "
            + ", ".join(unclassified)
        )
    producers: dict[str, dict[str, str]] = built["producers"]
    image = {
        "schema_version": SCHEMA_VERSION,
        "authority": (
            "Phase 1C classification of every mutating producer as leased (uses the "
            "canonical lease+intent path) or exempt (proven reason). Fails closed on "
            "any new unclassified producer."
        ),
        "producer_count": len(producers),
        "producers": producers,
    }
    from .guarded_registry_projection import (
        GuardedProjectionError, publish_guarded_registry_projection)
    try:
        result = publish_guarded_registry_projection(root, REGISTRY_RELATIVE, image,
            admission_event_id=admission_event_id)
    except GuardedProjectionError as error:
        raise MutatingProducerError(str(error)) from error
    return {**result, "producer_count": len(producers)}
