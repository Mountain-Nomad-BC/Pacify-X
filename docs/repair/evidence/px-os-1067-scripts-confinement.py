"""Classify each remaining scripts producer by what it ACTUALLY writes.

`static_disposition_class` was generated by an earlier audit heuristic. This derives the
class from observed facts instead: the destinations extracted from the source and whether
each one is caller-selected.

* every destination is inside the repository and none is caller-selected -> repository_state
* every caller-selected destination is confined by the producer's own code    -> confined_output
* some caller-selected destination is unconfined                               -> needs_confinement
* no statically visible destination                                            -> opaque

Read-only. No grant, no classification change.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))

from runtime.output_root_classification import produced_destinations  # noqa: E402

EVIDENCE = Path(__file__).parent
CENSUS = EVIDENCE / "px-os-1067-census-2026-11-03.json"

# A caller-selected destination is one derived from parsed arguments.
CALLER_MARKERS = ("args.", "namespace.", "opts.")


def classify(relative: str) -> dict[str, object]:
    destinations = produced_destinations(ROOT, relative)
    caller = [d for d in destinations if any(marker in d for marker in CALLER_MARKERS)]
    source = (ROOT / relative).read_text(encoding="utf-8-sig")
    confined = "relative_to(root" in source or "is_relative_to(root" in source
    if not destinations:
        kind = "opaque"
    elif caller:
        kind = "confined_output" if confined else "needs_confinement"
    else:
        kind = "repository_state"
    return {
        "path": relative,
        "kind": kind,
        "destinations": destinations[:10],
        "caller_destinations": caller[:6],
        "confines_to_root": confined,
    }


def main() -> int:
    document = json.loads(CENSUS.read_text(encoding="utf-8"))
    unresolved = [p for p in document["unresolved_paths"] if p.startswith("scripts/")]
    rows = [classify(relative) for relative in unresolved]
    totals: dict[str, int] = {}
    for row in rows:
        totals[row["kind"]] = totals.get(row["kind"], 0) + 1
    output = {
        "schema_version": "px.scripts-confinement-audit/1.0",
        "gap_id": "PX-OS-1067",
        "population": len(unresolved),
        "totals": totals,
        "producers": rows,
    }
    (EVIDENCE / "px-os-1067-scripts-confinement-audit.json").write_text(
        json.dumps(output, indent=1, sort_keys=True), encoding="utf-8"
    )
    print(json.dumps(totals))
    for row in rows:
        if row["kind"] == "needs_confinement":
            print(" needs_confinement", row["path"], row["caller_destinations"][:2])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
